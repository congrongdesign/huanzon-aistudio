import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createProject, createImageRecord, saveBinaryFile, resolveLocalFilePath, updateImageRecord, getImageRecordById, getLocalDataDirectory } from '../src/lib/local-backend';
import { changeStorageDirectory, scanStorage, cleanStorage, storageOverview } from '../src/lib/storage-management';
import { mediaRoot, mediaFolder } from '../src/lib/media-storage';
import { writeRuntimeConfig } from '../src/lib/runtime-config';
import { GET, POST } from '../src/app/api/storage-management/route';
import { NextRequest } from 'next/server';
import sharp from 'sharp';
import { saveFontImage, fontFilePath } from '../src/lib/font-library-store';
import { GET as getFontFile } from '../src/app/api/font-file/[key]/route';
import { browseStorageDirectory, createStorageDirectory, validateStorageDirectory } from '../src/lib/storage-directory-browser';
import { DESKTOP_GUEST_USER_ID } from '../src/lib/guest';

async function main() {
  const sandbox = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'hz-storage-')));
  process.env.LOCAL_DATA_DIR = path.join(sandbox, 'app');
  const owner = 'storage-qa';
  const project = createProject(owner, 'Storage QA');
  const old = saveBinaryFile(Buffer.from('original'), 'original.png');
  createImageRecord({ prompt: 'qa', user_id: owner, project_id: project.id, image_key: old.key, image_url: old.url });
  const pickerRoot = path.join(sandbox, 'picker'); await fs.mkdir(pickerRoot);
  await fs.mkdir(path.join(pickerRoot, '图片库')); await fs.mkdir(path.join(pickerRoot, '.hidden'));
  await fs.writeFile(path.join(pickerRoot, 'document.txt'), 'not a folder');
  await fs.symlink(path.join(pickerRoot, '图片库'), path.join(pickerRoot, 'linked-folder'));
  const listing = await browseStorageDirectory(pickerRoot);
  assert(listing.folders.some(folder => folder.name === '图片库'));
  assert(listing.folders.some(folder => folder.name === 'linked-folder'));
  assert(!listing.folders.some(folder => folder.name === '.hidden' || folder.name === 'document.txt'));
  assert.equal(listing.parent, sandbox);
  assert.equal(listing.breadcrumbs.at(-1)?.path, pickerRoot);
  assert.equal(listing.writable, true);
  await assert.rejects(() => validateStorageDirectory(path.join(getLocalDataDirectory(), 'files')), /独立文件夹/);
  const created = await createStorageDirectory(pickerRoot, '新建图片库');
  assert.equal(created.directory, path.join(pickerRoot, '新建图片库'));
  assert.equal((await validateStorageDirectory(created.directory)).directory, created.directory);
  assert.deepEqual(await fs.readdir(created.directory), []);
  assert.notEqual(mediaRoot(), created.directory, 'browsing and selection must not change saved location');
  await assert.rejects(() => createStorageDirectory(pickerRoot, '../escape'), /有效/);
  await assert.rejects(() => createStorageDirectory(pickerRoot, '新建图片库'), /同名/);
  await assert.rejects(() => validateStorageDirectory(path.parse(sandbox).root), /专用文件夹/);
  await assert.rejects(() => browseStorageDirectory('relative'), /地址无效/);
  const browseResponse = await POST(new NextRequest('http://192.168.1.206:3217/api/storage-management', { method: 'POST', body: JSON.stringify({ action: 'browse-directory', directory: pickerRoot }) }));
  assert.equal(browseResponse.status, 200); assert.equal((await browseResponse.json()).directory, pickerRoot);
  const next = path.join(sandbox, 'external');
  await changeStorageDirectory(next, false);
  assert.equal(await fs.readFile(resolveLocalFilePath(old.key), 'utf8'), 'original');
  const fresh = saveBinaryFile(Buffer.from('fresh'), 'fresh.png');
  assert.equal(path.dirname(resolveLocalFilePath(fresh.key)), path.join(next, 'files'));
  const orphan = saveBinaryFile(Buffer.from('orphan'), 'unused.png');
  const recent = saveBinaryFile(Buffer.from('recent'), 'recent.png');
  const protectedFile = saveBinaryFile(Buffer.from('draft'), 'draft.png');
  await fs.writeFile(path.join(getLocalDataDirectory(), 'draft.json'), JSON.stringify({ url: `/api/local-file/${protectedFile.key}` }));
  const ago = new Date(Date.now() - 48 * 3600_000);
  for (const key of [orphan.key, protectedFile.key]) await fs.utimes(resolveLocalFilePath(key), ago, ago);
  const outside = path.join(sandbox, 'never-delete.png'); await fs.writeFile(outside, 'protected');
  await fs.symlink(outside, path.join(next, 'files', 'symlink.png'));
  const cacheDir = path.join(getLocalDataDirectory(), 'preview-cache'); await fs.mkdir(cacheDir, { recursive: true });
  await fs.writeFile(path.join(cacheDir, 'a'.repeat(64) + '.webp'), 'cache'); await fs.utimes(path.join(cacheDir, 'a'.repeat(64) + '.webp'), ago, ago);
  const missing = createImageRecord({ prompt: 'qa', user_id: owner, project_id: project.id, image_key: 'missing.png' });
  const scan = await scanStorage(owner);
  assert.equal(scan.counts.orphans.count, 1);
  assert.equal(scan.counts.cache.count, 1);
  assert(scan.missing.some(item => item.id === missing.id));
  assert(!scan.items.some(item => item.name === recent.key || item.name === protectedFile.key || item.name === 'symlink.png'));
  await assert.rejects(() => cleanStorage('different-user', scan.token, scan.items.map(item => item.id)), /过期/);
  createImageRecord({ prompt: 'qa', user_id: owner, project_id: project.id, image_key: orphan.key, image_url: orphan.url });
  const clean = await cleanStorage(owner, scan.token, scan.items.map(item => item.id));
  assert.equal(clean.removed, 1); assert.equal(clean.skipped, 1);
  assert.equal(await fs.readFile(resolveLocalFilePath(orphan.key), 'utf8'), 'orphan');
  const trashFile = saveBinaryFile(Buffer.from('shared'), 'trash.png');
  const trash = createImageRecord({ prompt: 'qa', user_id: owner, image_key: trashFile.key, image_url: trashFile.url, deleted_at: new Date().toISOString() });
  await fs.writeFile(path.join(getLocalDataDirectory(), 'history.json'), JSON.stringify({ url: trashFile.url }));
  const trashScan = await scanStorage(owner);
  const trashResult = await cleanStorage(owner, trashScan.token, [trash.id]);
  assert.equal(trashResult.removed, 1); assert.equal(trashResult.bytes, 0);
  assert.equal(getImageRecordById(trash.id, owner), null);
  assert.equal(await fs.readFile(resolveLocalFilePath(trashFile.key), 'utf8'), 'shared');
  const restored = createImageRecord({ prompt: 'qa', user_id: owner, image_key: fresh.key, deleted_at: new Date().toISOString() });
  const restoredScan = await scanStorage(owner);
  updateImageRecord(restored.id, owner, { deleted_at: null });
  assert.equal((await cleanStorage(owner, restoredScan.token, [restored.id])).skipped, 1);
  await fs.writeFile(path.join(getLocalDataDirectory(), 'broken.json'), '{broken');
  await assert.rejects(() => scanStorage(owner), /索引无法读取/);
  await fs.unlink(path.join(getLocalDataDirectory(), 'broken.json'));
  const conflict = path.join(sandbox, 'conflict'); await fs.mkdir(path.join(conflict, 'files'), { recursive: true });
  await fs.writeFile(path.join(conflict, 'files', old.key), 'different');
  await assert.rejects(() => changeStorageDirectory(conflict, true), /同名文件/);
  assert.equal(mediaRoot(), next);
  const final = path.join(sandbox, 'final');
  const job = await changeStorageDirectory(final, true);
  while (job?.status === 'running') await new Promise(resolve => setTimeout(resolve, 20));
  assert.equal(job?.status, 'completed', job?.error);
  assert.equal(await fs.readFile(resolveLocalFilePath(old.key), 'utf8'), 'original');
  assert.equal(path.dirname(resolveLocalFilePath(old.key)), mediaFolder(final, 'files'));
  await assert.rejects(() => changeStorageDirectory(path.join(final, 'nested'), false), /相互包含/);
  await assert.rejects(() => changeStorageDirectory('relative/path', false), /绝对路径/);
  const back = await changeStorageDirectory('', true);
  while (back?.status === 'running') await new Promise(resolve => setTimeout(resolve, 20));
  assert.equal(back?.status, 'completed', back?.error);
  assert.equal(mediaRoot(), getLocalDataDirectory());
  assert.equal(await fs.readFile(outside, 'utf8'), 'protected');
  const overview = await storageOverview(); assert(overview.libraryCount > 0);
  const font = await saveFontImage(DESKTOP_GUEST_USER_ID, await sharp({ create: { width: 32, height: 32, channels: 4, background: '#ffffff' } }).png().toBuffer(), 'sample');
  await fs.unlink(fontFilePath(font.key) + '.128.webp');
  const rebuilt = await getFontFile(new NextRequest(`http://localhost:3217/api/font-file/${font.key}?w=128`), { params: Promise.resolve({ key: font.key }) });
  assert.equal(rebuilt.status, 200); assert((await rebuilt.arrayBuffer()).byteLength > 0);
  // Public addresses must work even when Next constructs an internal nextUrl.
  for (const [url, host, origin] of [
    ['http://192.168.1.206:3217', '192.168.1.206:3217', 'http://192.168.1.206:3217'],
    ['http://localhost:3217', '192.168.1.206:3217', 'http://192.168.1.206:3217'],
    ['http://localhost:3217', 'studio.example.com', 'https://studio.example.com'],
  ]) {
    const headers = { host, origin };
    const overviewResponse = await GET(new NextRequest(`${url}/api/storage-management`, { headers }));
    assert.equal(overviewResponse.status, 200);
    assert.equal((await overviewResponse.json()).supported, true);
    const scanResponse = await POST(new NextRequest(`${url}/api/storage-management`, { method: 'POST', headers, body: JSON.stringify({ action: 'scan' }) }));
    assert.equal(scanResponse.status, 200);
    assert.equal(typeof (await scanResponse.json()).token, 'string');
  }
  const forwarded = await POST(new NextRequest('http://localhost:3217/api/storage-management', { method: 'POST', headers: { 'x-hz-lan-proxy': '1' }, body: JSON.stringify({ action: 'scan' }) }));
  assert.equal(forwarded.status, 403);
  const crossSite = await GET(new NextRequest('http://192.168.1.206:3217/api/storage-management', { headers: { 'sec-fetch-site': 'cross-site' } }));
  assert.equal(crossSite.status, 403);
  const disconnected = path.join(sandbox, 'disconnected'); await changeStorageDirectory(disconnected, false); await fs.rmdir(disconnected);
  assert.throws(() => saveBinaryFile(Buffer.from('new'), 'offline.png'), /储存目录不可用/);
  const blocked = await POST(new NextRequest('http://localhost:3217/api/storage-management', { method: 'POST', headers: { origin: 'http://evil.example' }, body: JSON.stringify({ action: 'scan' }) }));
  assert.equal(blocked.status, 403);
  writeRuntimeConfig({ backendMode: 'lan', lanRole: 'client' });
  const unavailable = await GET(new NextRequest('http://localhost:3217/api/storage-management'));
  assert.equal((await unavailable.json()).supported, false);
  const clientWrite = await POST(new NextRequest('http://192.168.1.206:3217/api/storage-management', { method: 'POST', body: JSON.stringify({ action: 'scan' }) }));
  assert.equal(clientWrite.status, 403);
  await fs.rm(sandbox, { recursive: true, force: true });
  console.log('PASS: storage routing, old-file fallback, reference safety, grace period, symlink exclusion, stale selection, restored trash, shared files, corrupt indexes, conflicts, verified migration, default restore, origin guard, LAN scope');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
