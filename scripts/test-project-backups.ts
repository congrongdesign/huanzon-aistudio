import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import sharp from 'sharp';
import JSZip from 'jszip';
import { NextRequest } from 'next/server';
import { createProject, createImageRecord, createCanvasBlock, createChatMessage, getProjectById, exportLocalProjectSnapshot, resolveLocalFilePath, saveBinaryFile } from '../src/lib/local-backend';
import { buildProjectArchive, importProjectArchiveBuffer, verifyProjectArchiveBuffer } from '../src/lib/project-archive';
import { listArchiveEntries, readArchiveEntryBuffer, writeArchivePackage, writeArchiveConfig, getArchiveJob } from '../src/lib/project-archive-store';
import { projectBackupCards } from '../src/lib/project-backup-cards';
import { GET, POST } from '../src/app/api/project-archive/route';
import { GET as exportPackage, POST as importPackage } from '../src/app/api/project-package/route';
import { DESKTOP_GUEST_USER_ID } from '../src/lib/guest';
import { backupWorkerRequest, refreshBackupCatalog } from '../src/lib/project-backup-service';
import type { Project } from '../src/lib/types';

async function main() {
  const temp = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'hz-backups-')));
  process.env.LOCAL_DATA_DIR = path.join(temp, 'app');
  process.env.DESKTOP_GUEST_MODE = '1';
  const owner = DESKTOP_GUEST_USER_ID;
  const root = path.join(temp, 'AIstudio备份'); await fs.mkdir(root);
  const project = createProject(owner, '备份测试');
  const block = createCanvasBlock({ user_id: owner, project_id: project.id, canvas_x: 123, name: '主画板' });
  // Incompressible pixels force multiple write chunks, unlike a tiny solid PNG.
  const png = await sharp(randomBytes(720 * 640 * 3), { raw: { width: 720, height: 640, channels: 3 } }).png().toBuffer();
  assert(png.length > 1024 * 1024);
  const image = saveBinaryFile(png, 'test.png');
  createImageRecord({ user_id: owner, project_id: project.id, image_key: image.key, image_url: image.url, canvas_x: 123, canvas_y: 456, canvas_block_id: block.id, prompt: 'sample', status: 'completed' });
  createChatMessage(project.id, owner, 'user', '恢复后继续编辑');
  const built = await buildProjectArchive({ projectId: project.id, userId: owner, baseUrl: 'http://localhost' });
  const verified = await verifyProjectArchiveBuffer(built.buffer);
  assert.equal(verified.data.canvasBlocks[0].name, '主画板');
  writeArchiveConfig(root);
  const saved = await writeArchivePackage(root, built.buffer, built.fileName, built.manifest);
  let entries = await listArchiveEntries(root);
  assert.equal(entries.length, 1);
  assert(entries[0].thumbnailDataUrl?.startsWith('data:image/webp;base64,'));
  const restored = await importProjectArchiveBuffer(readArchiveEntryBuffer(root, entries[0]), owner);
  assert.equal(restored.restoredAsCopy, true);
  assert.notEqual(restored.project.id, project.id);
  assert.equal(restored.project.name, '备份测试（恢复副本）');
  const snapshot = exportLocalProjectSnapshot(String(restored.project.id), owner);
  assert.equal(snapshot.imageRecords[0].canvas_x, 123); assert.equal(snapshot.imageRecords[0].canvas_y, 456);
  assert.equal(snapshot.imageRecords[0].canvas_block_id, snapshot.canvasBlocks[0].id);
  assert.equal(snapshot.chatMessages[0].content, '恢复后继续编辑');
  assert.deepEqual(await fs.readFile(resolveLocalFilePath(String(snapshot.imageRecords[0].image_key))), png);
  assert(getProjectById(project.id, owner), 'backup/restore must retain original');
  const second = await buildProjectArchive({ projectId: project.id, userId: owner, baseUrl: 'http://localhost' });
  await writeArchivePackage(root, second.buffer, second.fileName, second.manifest);
  entries = await listArchiveEntries(root);
  const cards = projectBackupCards([project as unknown as Project], entries);
  assert.equal(cards.length, 1); assert.equal(cards[0].versions.length, 2);
  const legacy = new JSZip();
  legacy.file('assets/one.png', png);
  legacy.file('manifest.json', JSON.stringify({ format: 'huanzon-aistudio-project', version: 1, exportedAt: new Date().toISOString(), project: { id: 'old-project', name: '旧同步', user_id: owner }, imageRecords: [{ id: 'old-image', image_url: 'https://old/one.png', canvas_x: 17 }], assets: [{ fileName: 'assets/one.png', originalUrl: 'https://old/one.png', contentType: 'image/png' }] }));
  const legacyBytes = await legacy.generateAsync({ type: 'nodebuffer' });
  await fs.writeFile(path.join(root, '旧项目.hzproj.zip'), legacyBytes);
  entries = await listArchiveEntries(root);
  const oldEntry = entries.find(entry => entry.sourceFormat === 'legacy'); assert(oldEntry?.thumbnailDataUrl);
  const preparedLegacy = await backupWorkerRequest<{ prepared: { manifest: { data: { imageRecords: { canvas_x: number }[] } }; options: { assetByOriginalUrl: [string, { key: string }][] } } }>({ action: 'prepare-restore', root, userId: owner, entryId: oldEntry.id });
  assert.equal(preparedLegacy.prepared.manifest.data.imageRecords[0].canvas_x, 17);
  assert.deepEqual(await fs.readFile(resolveLocalFilePath(preparedLegacy.prepared.options.assetByOriginalUrl[0][1].key)), png);
  assert.equal(getProjectById('old-project', owner), null, 'worker must not modify the project database');
  const oldRestored = await importProjectArchiveBuffer(legacyBytes, owner);
  assert.equal(oldRestored.project.id, 'old-project');
  assert.equal(exportLocalProjectSnapshot('old-project', owner).imageRecords[0].canvas_x, 17);
  legacy.remove('assets/one.png');
  const broken = await legacy.generateAsync({ type: 'nodebuffer' });
  await assert.rejects(() => importProjectArchiveBuffer(broken, owner), /缺少资源/);
  const request = (body: object) => POST(new NextRequest('http://localhost/api/project-archive', { method: 'POST', body: JSON.stringify(body) }));
  const response = await request({ action: 'archive', projectIds: [project.id], targetDir: root, deleteAfterBackup: false });
  assert.equal(response.status, 200);
  const jobId = (await response.json()).jobId;
  for (let n = 0; n < 300 && ['queued', 'running'].includes(getArchiveJob(jobId)?.status || ''); n++) await new Promise(resolve => setTimeout(resolve, 20));
  const job = getArchiveJob(jobId); assert.equal(job?.status, 'completed', JSON.stringify(job));
  assert.equal(job?.results[0].originalRemoved, false); assert(getProjectById(project.id, owner));
  const exported = await exportPackage(new NextRequest(`http://localhost/api/project-package?projectId=${project.id}`));
  assert.equal(exported.status, 200);
  const portable = Buffer.from(await exported.arrayBuffer());
  assert.equal((await verifyProjectArchiveBuffer(portable)).data.canvasBlocks.length, 1);
  const form = new FormData(); form.set('file', new File([portable], 'test.hzarchive.zip'));
  const imported = await importPackage(new NextRequest('http://localhost/api/project-package', { method: 'POST', body: form }));
  assert.equal(imported.status, 200);
  const invalidProject = createProject(owner, '缺原图'); createImageRecord({ user_id: owner, project_id: invalidProject.id, image_key: 'missing.png', prompt: 'missing' });
  await assert.rejects(() => buildProjectArchive({ projectId: invalidProject.id, userId: owner, baseUrl: 'http://localhost' }), /图片不存在/);
  assert(getProjectById(invalidProject.id, owner));
  const historyProject = createProject(owner, '历史链接缺失');
  createImageRecord({ user_id: owner, project_id: historyProject.id, image_key: image.key, image_url: image.url, reference_images: '["/api/local-file/deleted-reference.png"]', prompt: 'keep original', status: 'completed' });
  createChatMessage(historyProject.id, owner, 'assistant', '旧图片已经删除，保留这段对话', null, '/api/local-file/deleted-result.png');
  const historyBackup = await buildProjectArchive({ projectId: historyProject.id, userId: owner, baseUrl: 'http://localhost' });
  const historyManifest = await verifyProjectArchiveBuffer(historyBackup.buffer);
  assert.equal(historyManifest.missingHistoryAssets?.length, 2);
  assert.equal(historyManifest.data.chatMessages[0].content, '旧图片已经删除，保留这段对话');
  assert.equal(historyManifest.assets.length, 1, 'current canvas image must still be packaged');
  const historyEntry = await writeArchivePackage(root, historyBackup.buffer, historyBackup.fileName, historyBackup.manifest);
  assert.equal(historyEntry.missingHistoryAssetCount, 2);
  const historyRestored = await importProjectArchiveBuffer(historyBackup.buffer, owner);
  const historySnapshot = exportLocalProjectSnapshot(String(historyRestored.project.id), owner);
  assert.equal(historySnapshot.chatMessages[0].content, historyManifest.data.chatMessages[0].content);
  assert.deepEqual(await fs.readFile(resolveLocalFilePath(String(historySnapshot.imageRecords[0].image_key))), png);
  const packagePath = path.join(root, saved.relativePath); await fs.appendFile(packagePath, 'corruption');
  assert.throws(() => readArchiveEntryBuffer(root, saved), /校验失败/);
  await fs.rename(root, root + '-offline');
  // UI reads the local catalog immediately; offline detection runs separately.
  await assert.rejects(() => backupWorkerRequest({ action: 'scan', root }));
  refreshBackupCatalog(root, true);
  await new Promise(resolve => setTimeout(resolve, 800));
  const offline = await GET(new NextRequest('http://localhost/api/project-archive')); assert.equal((await offline.json()).ready, false);
  await assert.rejects(() => fs.stat(root));
  await fs.mkdir(root);
  await assert.rejects(() => listArchiveEntries(root), /身份不匹配/);
  assert.equal((await fs.readdir(root)).length, 0);
  await fs.rm(temp, { recursive: true, force: true });
  // Allow the archive worker to finish its bounded idle check before deleting its store.
  await new Promise(resolve => setTimeout(resolve, 450));
  console.log('PASS: v1/v2 discovery, cached thumbnails, per-project versions, full portable export/import, canvas relationships, original retention, missing assets, corruption, offline NAS, repository identity');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
